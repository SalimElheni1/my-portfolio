#!/usr/bin/env bash
# Writes /etc/nginx/conf.d/cloudflare-realip.conf from Cloudflare's published
# address ranges, so nginx sees each visitor's real address instead of a
# Cloudflare edge server's. Without it every visitor shares a few addresses
# and the contact form's per-visitor rate limit stops telling them apart.
#
# Run as root once at setup, then weekly from cron:
#   0 4 * * 1 /var/www/portfolio/update-cloudflare-ips.sh
set -euo pipefail

out=/etc/nginx/conf.d/cloudflare-realip.conf
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

{
  echo "# Generated by update-cloudflare-ips.sh on $(date -u +%F). Do not edit."
  for list in ips-v4 ips-v6; do
    curl -fsS --max-time 20 "https://www.cloudflare.com/$list" | while read -r range; do
      [ -n "$range" ] && echo "set_real_ip_from $range;"
    done
  done
  echo "real_ip_header CF-Connecting-IP;"
} > "$tmp"

# Refuse to install a list that came back empty or truncated.
if [ "$(grep -c '^set_real_ip_from' "$tmp")" -lt 10 ]; then
  echo "Cloudflare IP list looks wrong; keeping the current one." >&2
  exit 1
fi

if ! cmp -s "$tmp" "$out" 2>/dev/null; then
  install -m 644 "$tmp" "$out"
  nginx -t && systemctl reload nginx
fi
